#!/bin/bash

VIDEO="$1"

# ============================================================
# chafa 動画プレーヤー
#
# ffmpegで1フレームずつJPEGを生成
# → chafaで表示
# → 表示済みJPEGを削除
# ============================================================


# ============================================================
# 動画ファイル確認
# ============================================================

if [ ! -f "$VIDEO" ]; then

    echo "Video not found:"
    echo "$VIDEO"
    echo

    read -p "Press Enter to close..."

    exit 1
fi


# ============================================================
# 一時ディレクトリ
# ============================================================

TEMP_DIR=$(mktemp -d)

cleanup()
{
    rm -rf "$TEMP_DIR"
}

trap cleanup EXIT


# ============================================================
# ffmpeg
# ============================================================

ffmpeg \
    -loglevel error \
    -i "$VIDEO" \
    -vf "fps=5" \
    "$TEMP_DIR/frame_%06d.jpg" &

FFMPEG_PID=$!


# ============================================================
# フレーム再生
# ============================================================

FRAME_NUMBER=1

while true
do

    FRAME=$(printf \
        "%s/frame_%06d.jpg" \
        "$TEMP_DIR" \
        "$FRAME_NUMBER"
    )


    # --------------------------------------------------------
    # フレームが生成されるまで待つ
    # --------------------------------------------------------

    while [ ! -f "$FRAME" ]
    do

        if ! kill -0 "$FFMPEG_PID" 2>/dev/null
        then

            # ffmpeg終了後、最後のフレームがなければ終了
            if [ ! -f "$FRAME" ]; then
                break 2
            fi

        fi

        sleep 0.02

    done


    # --------------------------------------------------------
    # 画面を消す
    # --------------------------------------------------------

    clear


    # --------------------------------------------------------
    # chafaで表示
    # --------------------------------------------------------

    chafa "$FRAME"

    CHAFFA_STATUS=$?

    if [ "$CHAFFA_STATUS" -ne 0 ]; then

        echo
        echo "chafa error."
        echo "Exit code: $CHAFFA_STATUS"
        echo

        break

    fi


    # --------------------------------------------------------
    # 表示したJPEGを削除
    # --------------------------------------------------------

    rm -f "$FRAME"


    FRAME_NUMBER=$((FRAME_NUMBER + 1))


    # --------------------------------------------------------
    # 5fps
    # --------------------------------------------------------

    sleep 0.2

done


# ============================================================
# ffmpeg終了待ち
# ============================================================

wait "$FFMPEG_PID" 2>/dev/null

FFMPEG_STATUS=$?


# ============================================================
# 念のため残ったJPEGを削除
# ============================================================

rm -f "$TEMP_DIR"/frame_*.jpg


# ============================================================
# 終了メッセージ
# ============================================================

echo
echo
echo "================================"

if [ "$FFMPEG_STATUS" -eq 0 ]; then

    echo "End of video."
    echo "ffmpeg exit code: 0"

else

    echo "Video playback error."
    echo "ffmpeg exit code: $FFMPEG_STATUS"

fi

echo "================================"
echo
echo "Press Enter to close."

read
